const fs = require('fs');
const path = require('path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const schema = JSON.parse(fs.readFileSync(path.join(root, 'nodes/agent_input/portfolio_manager_output_schema.json'), 'utf8'));
const code = fs.readFileSync(path.join(root, 'nodes/agent_input/claude_messages_decode.code.js'), 'utf8');
const run = input => new Function('$json', 'SCHEMA', code)(input, schema)[0].json;
const decision = {marketRegime: 'NEUTRAL', targetExposurePct: 50, maxNewPositions: 0, actions: [], riskNotes: [], dataCaveats: []};
const response = output => ({model: 'claude-opus-5-5', stop_reason: 'end_turn', content: [{type: 'thinking', thinking: '', signature: 'test'}, {type: 'text', text: JSON.stringify(output)}], usage: {input_tokens: 10, output_tokens: 20}});
assert.deepEqual(run(response(decision)).output, decision);
assert.equal(run({...response(decision), stop_reason: 'max_tokens'}).error, 'ANTHROPIC_STOP_max_tokens');
assert.equal(run({...response(decision), stop_reason: 'refusal'}).error, 'ANTHROPIC_STOP_refusal');
assert.equal(run({...response(decision), model: 'claude-opus-4-8'}).error, 'ANTHROPIC_MODEL_MISMATCH');
assert.equal(run({error: 'provider failure'}).error, 'ANTHROPIC_UPSTREAM_ERROR');
assert.match(run(response({...decision, targetExposurePct: 101})).error, /above maximum/);
assert.match(run(response({...decision, maxNewPositions: 1.5})).error, /invalid type/);
const missing = {...decision}; delete missing.actions;
assert.match(run(response(missing)).error, /required/);
assert.match(run(response({...decision, riskNotes: Array(11).fill('note')})).error, /too many items/);
assert.ok(run({...response(decision), content: [{type: 'text', text: '{}{}'}]}).error);
console.log(JSON.stringify({ok: true, cases: 10}));
